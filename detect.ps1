#region connection
$tenantId = "REPLACE-WITH-YOUR-TENANT-ID"
$clientId = "REPLACE-WITH-YOUR-CLIENT-ID"
$clientSecret = "REPLACE-WITH-YOUR-CLIENT-SECRET"

#Start-Transcript -Path "C:\ProgramData\Microsoft\IntuneManagementExtension\Logs\AdminGroupRemediation-Detect.log" -Append

$autoCreateGroups = $false #Set to $true for DEV tenant to auto-create missing groups
$logMsg = @()
#endregion

#region main
try {
    $productName = (Get-ItemProperty -Path "HKLM:\SOFTWARE\COMPANY\DigitalWorkplace" -Name "ProductName" -ErrorAction Stop).ProductName
} catch {
    $productName = $null
}

$clientGroupName = "Admin-$($ENV:COMPUTERNAME)"                         # Will be member of local administrators
$adminGroupName = "Admin-Windows-$($productName)"                       # Will be member of local administrators
$remoteGroupName = "Admin-Intune-RemoteAccess-$($productName)"           # Will be member of local Remote Desktop Users and Remote Management Users
$clientGroupState = $false
$adminGroupState = $false
$remoteGroupState = $false
$remoteMgmtGroupState = $false

if ($autoCreateGroups -eq $true) {
    Start-Transcript -Path "C:\ProgramData\Microsoft\IntuneManagementExtension\Logs\AdminGroupRemediation-Detect.log" -Append

    $clientGroupName = "DEV-Admin-$($ENV:COMPUTERNAME)"
    $adminGroupName = "DEV-Admin-Windows-$($productName)"
    $remoteGroupName = "DEV-Admin-Intune-RemoteAccess-$($productName)"
}

$body = @{
    grant_type    = "client_credentials"
    scope         = "https://graph.microsoft.com/.default"
    client_id     = $clientId
    client_secret = $clientSecret
}

$tokenResponse = Invoke-RestMethod -Method Post -Uri "https://login.microsoftonline.com/$tenantId/oauth2/v2.0/token" -Body $body
$accessToken = $tokenResponse.access_token

Add-Type -AssemblyName System.Web

$headers = @{
    Authorization = "Bearer $accessToken"
}

# Check if the client group exists and get its SID
$logMsg += "Checking for existence of Client group '$clientGroupName' in Entra ID..."
$clientGroupgraphUrl = "https://graph.microsoft.com/v1.0/groups?`$filter=displayName eq '$clientGroupName'"
$clientGroupgroupInfo = Invoke-RestMethod -Uri $clientGroupgraphUrl -Headers $headers -Method Get
$clientGroupGroupSID = $clientGroupgroupInfo.value.securityIdentifier

if ($null -eq $clientGroupGroupSID) {
    $logMsg += "Client group not yet created"
    if ($autoCreateGroups) {
        $logMsg += "Running in DEV mode, attempting to create Client group in Entra ID"
        if (!$groupInfo.value -or $groupInfo.value.Count -eq 0) {
            #Create group in entra id because it does not exists
            $groupBody = @{
                displayName     = $clientGroupName
                mailEnabled     = $false
                mailNickname    = $clientGroupName
                securityEnabled = $true
                description     = "Members of this group are granted local administrator permissions on $($ENV:COMPUTERNAME). This group has been auto-generated by the test_configure_admin-group Remediation in the Intune DEV tenant."
            } | ConvertTo-Json

            $headers = @{
                Authorization  = "Bearer $accessToken"
                "Content-Type" = "application/json"
            }

            Invoke-RestMethod -Method Post -Uri "https://graph.microsoft.com/v1.0/groups" -Headers $headers -Body $groupBody
            $groupInfo = Invoke-RestMethod -Uri $graphUrl -Headers $headers -Method Get
        }
    }
    #exit 0
} else {
    $logMsg += "$clientGroupName ($($clientGroupGroupSID))"
}

$clientGroupMembers = Get-LocalGroupMember -SID "S-1-5-32-544"
$clientGroupexists = $clientGroupMembers | Where-Object { $_.Name -eq $clientGroupGroupSID }
$logMsg += "Client group configured: $(if ($clientGroupexists) { 'Yes' } else { 'No' })"
$clientGroupState = $(if ($clientGroupexists) { $true } else { $false })


if ($null -ne $productName) {
    # Check if the admin group exists and get its SID
    $logMsg += "Checking for existence of Admin group '$adminGroupName' in Entra ID..."
    $adminGroupgraphUrl = "https://graph.microsoft.com/v1.0/groups?`$filter=displayName eq '$adminGroupName'"
    $adminGroupgroupInfo = Invoke-RestMethod -Uri $adminGroupgraphUrl -Headers $headers -Method Get
    $adminGroupGroupSID = $adminGroupgroupInfo.value.securityIdentifier

    if ($null -eq $adminGroupGroupSID) {
        $logMsg += "Admin group not yet created"
        if ($autoCreateGroups) {
            $logMsg += "Running in DEV mode, attempting to create Admin group in Entra ID"
            if (!$groupInfo.value -or $groupInfo.value.Count -eq 0) {
                #Create group in entra id because it does not exists
                $groupBody = @{
                    displayName     = $adminGroupName
                    mailEnabled     = $false
                    mailNickname    = $adminGroupName
                    securityEnabled = $true
                    description     = "Members of this group are granted local administrator permissions on all $($productName)-Clients. This group has been auto-generated by the test_configure_admin-group Remediation."
                } | ConvertTo-Json

                $headers = @{
                    Authorization  = "Bearer $accessToken"
                    "Content-Type" = "application/json"
                }

                Invoke-RestMethod -Method Post -Uri "https://graph.microsoft.com/v1.0/groups" -Headers $headers -Body $groupBody
                $groupInfo = Invoke-RestMethod -Uri $graphUrl -Headers $headers -Method Get
            }
        }
        #exit 0
    } else {
        $logMsg += "$adminGroupName ($($adminGroupGroupSID))"
    }

    $adminGroupMembers = Get-LocalGroupMember -SID "S-1-5-32-544"
    $adminGroupexists = $adminGroupMembers | Where-Object { $_.Name -eq $adminGroupGroupSID }
    $logMsg += "Admin group configured: $(if ($adminGroupexists) { 'Yes' } else { 'No' })"
    $adminGroupState = $(if ($adminGroupexists) { $true } else { $false })

    # Check if the remote group exists and get its SID
    $logMsg += "Checking for existence of Remote group '$remoteGroupName' in Entra ID..."
    $remoteGroupgraphUrl = "https://graph.microsoft.com/v1.0/groups?`$filter=displayName eq '$remoteGroupName'"
    $remoteGroupgroupInfo = Invoke-RestMethod -Uri $remoteGroupgraphUrl -Headers $headers -Method Get
    $remoteGroupGroupSID = $remoteGroupgroupInfo.value.securityIdentifier

    if ($null -eq $remoteGroupGroupSID) {
        $logMsg += "Remote group not yet created"
        if ($autoCreateGroups) {
            $logMsg += "Running in DEV mode, attempting to create Remote group in Entra ID"
            if (!$groupInfo.value -or $groupInfo.value.Count -eq 0) {
                #Create group in entra id because it does not exists
                $groupBody = @{
                    displayName     = $remoteGroupName
                    mailEnabled     = $false
                    mailNickname    = $remoteGroupName
                    securityEnabled = $true
                    description     = "Members of this group are granted remote access using RDP and WinRM on all $($productName)-Clients. This group has been auto-generated by the test_configure_admin-group Remediation."
                } | ConvertTo-Json

                $headers = @{
                    Authorization  = "Bearer $accessToken"
                    "Content-Type" = "application/json"
                }

                Invoke-RestMethod -Method Post -Uri "https://graph.microsoft.com/v1.0/groups" -Headers $headers -Body $groupBody
                $groupInfo = Invoke-RestMethod -Uri $graphUrl -Headers $headers -Method Get
            }
        }
        #exit 0
    } else {
        $logMsg += "$remoteGroupName ($($remoteGroupGroupSID))"
    }

    $remoteGroupMembers = Get-LocalGroupMember -SID "S-1-5-32-555"
    $remoteGroupexists = $remoteGroupMembers | Where-Object { $_.Name -eq $remoteGroupGroupSID }
    $logMsg += "Remote group configured: $(if ($remoteGroupexists) { 'Yes' } else { 'No' })"
    $remoteGroupState = $(if ($remoteGroupexists) { $true } else { $false })

    $remoteMgmtGroupMembers = Get-LocalGroupMember -SID "S-1-5-32-580"
    $remoteMgmtGroupexists = $remoteMgmtGroupMembers | Where-Object { $_.Name -eq $remoteGroupGroupSID }
    $logMsg += "RemoteMgmt group configured: $(if ($remoteMgmtGroupexists) { 'Yes' } else { 'No' })"
    $remoteMgmtGroupState = $(if ($remoteMgmtGroupexists) { $true } else { $false })
} else {
    $logMsg += "Policy for product bundle name not applied, skipping local admin productbundlegroup management"
}
#endregion

#region remediation output
$logMsgOut = $logMsg -join "`n"


if ($clientGroupexists -and $adminGroupexists -and $remoteGroupexists -and $remoteMgmtGroupexists) {
    Write-Output "Local groups are already configured:`n$logMsgOut"
    Write-Output "ClientAdmin: $($clientGroupState), PBAdmin: $($adminGroupState), RDPUsers: $($remoteGroupState), RemoteMgmtUsers: $($remoteMgmtGroupState)"
    if ($autoCreateGroups -eq $true) { Stop-Transcript | Out-Null }
    exit 0
} else {
    Write-Output "Local groups need to be configured:`n$logMsgOut"
    Write-Output "ClientAdmin: $($clientGroupState), PBAdmin: $($adminGroupState), RDPUsers: $($remoteGroupState), RemoteMgmtUsers: $($remoteMgmtGroupState)"
    if ($autoCreateGroups -eq $true) { Stop-Transcript | Out-Null }
    exit 1
}
#endregion

#Stop-Transcript